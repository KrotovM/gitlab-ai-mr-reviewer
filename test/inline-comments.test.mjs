// Fake GitLab: records reads and writes; serves the MR, paginated threads and failures from `state`.
let reads = [];
function fakeGitLab({ mrRefs = refs, pages = [[]], rejectLine, threadsFail = false, mrFail = false } = {}) {
  const writes = [];
  reads = [];
  globalThis.fetch = async (url, init = {}) => {
    const u = new URL(String(url));
    const method = init.method ?? "GET";
    if (method === "GET") reads.push(u.pathname.split("/").pop() + (u.searchParams.get("page") ?? ""));
    if (method !== "GET") {
      const body = init.body && JSON.parse(init.body);
      writes.push({ method, path: u.pathname + u.search, body });
      if (body?.position?.new_line === rejectLine) return new Response("line_code is invalid", { status: 400 });
      return Response.json({}, { status: method === "POST" ? 201 : 200 });
    }
    if (u.pathname.endsWith("/merge_requests/7")) {
      return mrFail ? new Response("boom", { status: 500 }) : Response.json({ diff_refs: mrRefs });
    }
    if (u.pathname.endsWith("/discussions")) {
      if (threadsFail) return new Response("boom", { status: 500 });
      const page = Number(u.searchParams.get("page"));
      const next = page < pages.length ? String(page + 1) : "";
      return Response.json(pages[page - 1] ?? [], { headers: { "x-next-page": next } });
    }
    return new Response("not found", { status: 404 });
  };
  return writes;
}
const run = (answer) =>
  postInlineFindings({
    answer,
    changes,
    diffRefs: refs,
    gitLabProjectApiUrl: new URL("https://gitlab.example.com/api/v4/projects/1"),
    headers: { "PRIVATE-TOKEN": "t" },
    mergeRequestIid: "7",
    logStep: () => {},
  });
const comment = (findings) =>
  `### 🤖 AI Code Review\n\n> summary\n\n${findings.map(renderReviewFinding).join("\n\n")}\n\n---\n_This comment was generated by AI review bot._`;

test("postInlineFindings: posts threads, resolves outdated ones, trims the summary", async () => {
  const [posted, rejected, known, kept] = [
    finding("src/a.ts", "~2"),
    finding("src/a.ts", "~5"),
    finding("src/a.ts", "~22"),
    finding("src/a.ts", "~10"),
  ];
  // The open thread at line 21 is on page 2, behind a short first page.
  const writes = fakeGitLab({
    pages: [[thread("stale", 3, { at: older, replies: [systemNote] })], [thread("open", 21)]],
    rejectLine: 5,
  });
  const summary = await run(comment([posted, rejected, known, kept]));

  // Threads are listed before the MR is re-read, so a push in between stops the run.
  assert.deepEqual(reads, ["discussions1", "discussions2", "7"]);
  assert.deepEqual(writes.map((w) => `${w.method} ${w.path}`), [
    "POST /api/v4/projects/1/merge_requests/7/discussions",
    "POST /api/v4/projects/1/merge_requests/7/discussions",
    "PUT /api/v4/projects/1/merge_requests/7/discussions/stale?resolved=true",
    "POST /api/v4/projects/1/merge_requests/7/discussions/stale/notes",
  ]);
  assert.equal(writes[0].body.body, `${renderReviewFinding(posted)}\n\n${INLINE_MARKER}`);
  assert.equal(writes[0].body.position.new_line, 2);
  assert.match(writes[3].body.body, /^Resolved automatically/);
  assert.equal(
    summary,
    `### 🤖 AI Code Review\n\n> summary\n\n${renderReviewFinding(rejected)}\n\n${renderReviewFinding(kept)}\n\n💬 Diff threads: 1 new, 1 already reported (open or resolved), 1 outdated resolved.\n\n---\n_This comment was generated by AI review bot._`,
  );
});

test("postInlineFindings: falls back to the full summary without writing anything", async () => {
  const answer = comment([finding("src/a.ts", "~2")]);
  const cases = {
    "newer push": { mrRefs: { ...refs, head_sha: "h3" } },
    "target branch moved": { mrRefs: { ...refs, base_sha: "b2" } },
    "threads unavailable": { threadsFail: true },
    "MR unavailable": { mrFail: true },
  };
  for (const [name, state] of Object.entries(cases)) {
    const writes = fakeGitLab(state);
    assert.equal(await run(answer), answer, name);
    assert.deepEqual(writes, [], name);
  }
});

test("postInlineFindings: findings that are not rendered blocks stay in the summary and keep threads open", async () => {
  // Raw labelled findings (consolidation failed): moving them would leave copies behind.
  const raw = "### 🤖 AI Code Review\n\n> summary\n\n- [high] Added line bug\n  File: src/a.ts\n  Line: ~2\n  Why: b changed.\n\n---\n_This comment was generated by AI review bot._";
  const writes = fakeGitLab({ pages: [[thread("stale", 3, { at: older })]] });
  assert.equal(await run(raw), raw);
  assert.deepEqual(writes, []);
});

test("postInlineFindings: never resolves threads after a failed review", async () => {
  for (const triageSummary of ["summary", "All clear, nothing to report"]) {
    const writes = fakeGitLab({ pages: [[thread("stale", 3, { at: older })]] });
    const failed = `### 🤖 AI Code Review\n\n> ${triageSummary}\n\nAI review could not be completed. Please ask a human to review this code change.`;
    assert.equal(await run(failed), failed, triageSummary);
    assert.deepEqual(writes, [], triageSummary);
  }
});
