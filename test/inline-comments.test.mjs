// Run with `pnpm test` (builds dist first).
import { test } from "node:test";
import assert from "node:assert/strict";
import {
  INLINE_MARKER,
  mapNewLines,
  planInlineComments,
  postInlineFindings,
} from "../dist/cli/inline-comments.js";
import { parseReviewFindings, renderReviewFinding } from "../dist/prompt/utils.js";
import { listMergeRequestDiscussions, postMergeRequestNote } from "../dist/gitlab/services.js";

const diff = [
  "@@ -1,4 +1,5 @@",
  " const a = 1;",
  "-const b = 2;",
  "+const b = 3;",
  "+const c = 4;",
  " const d = 5;",
  " const e = 6;",
  "@@ -20,2 +21,3 @@",
  " x();",
  "+y();",
  " z();",
  "@@ -40,2 +42,3 @@",
  " p();",
  "+q();",
  " r();",
  "\\ No newline at end of file",
].join("\n");
const refs = { base_sha: "b", start_sha: "s", head_sha: "h2" };
const older = { ...refs, head_sha: "h1" };
const changes = [
  { old_path: "src/a.ts", new_path: "src/a.ts", diff },
  { old_path: "gone.ts", new_path: "gone.ts", diff: "@@ -1 +0,0 @@\n-x", deleted_file: true },
];
const finding = (file, line, why = "because") => ({ severity: "high", title: `bug at ${line}`, file, line, why });
const systemNote = { body: "changed this line in version 2 of the diff", system: true };
const humanReply = { body: "is this still a problem?", system: false };
// A thread whose first note carries our marker (unless marker: false); `replies` follow it.
const thread = (id, new_line, { at = refs, resolved = false, marker = true, replies = [] } = {}) => ({
  id,
  notes: [
    { body: marker ? `x\n\n${INLINE_MARKER}` : "a human comment", system: false, resolved, position: { new_path: "src/a.ts", new_line, ...at } },
    ...replies,
  ],
});

test("mapNewLines: added lines map to null, context lines to their old line", () => {
  assert.deepEqual(
    [...mapNewLines(diff)],
    [[1, 1], [2, null], [3, null], [4, 3], [5, 4], [21, 20], [22, null], [23, 21], [42, 40], [43, null], [44, 41]],
  );
});

test("planInlineComments: post new, skip known (open or dismissed), resolve untouched outdated threads", () => {
  const [onAdded, onContext, nearOpen, nearDismissed, outsideDiff, deletedFile, unknownFile] = [
    finding("src/a.ts", "~2"),
    finding("`./src/a.ts`", "5"),
    finding("src/a.ts", "~22"),
    finding("src/a.ts", "~43"),
    finding("src/a.ts", "~10"),
    finding("gone.ts", "~1"),
    finding("other.ts", "~1"),
  ];
  const plan = planInlineComments({
    findings: [onAdded, onContext, nearOpen, nearDismissed, outsideDiff, deletedFile, unknownFile],
    changes,
    refs,
    discussions: [
      thread("open", 21),
      thread("dismissed", 44, { resolved: true }),
      thread("human", 2, { marker: false }),
      thread("stale", 3, { at: older, replies: [systemNote] }),
      thread("stale-base", 4, { at: { ...refs, base_sha: "b0" } }),
      thread("stale-replied", 1, { at: older, replies: [systemNote, humanReply] }),
      thread("stale-resolved", 5, { at: older, resolved: true }),
    ],
  });
  const at = { position_type: "text", ...refs, old_path: "src/a.ts", new_path: "src/a.ts" };
  assert.deepEqual(plan.post, [
    { finding: onAdded, position: { ...at, new_line: 2 } },
    { finding: onContext, position: { ...at, new_line: 5, old_line: 4 } },
  ]);
  assert.deepEqual(plan.known, [nearOpen, nearDismissed]);
  assert.deepEqual(plan.resolve, ["stale", "stale-base"]);
});

test("planInlineComments: the same place means within 3 lines", () => {
  const plan = (threadLine) =>
    planInlineComments({ findings: [finding("src/a.ts", "~2")], changes, refs, discussions: [thread("t", threadLine)] });
  assert.equal(plan(5).known.length, 1);
  assert.equal(plan(6).post.length, 1);
});

test("parseReviewFindings reads back a rendered finding whose why starts with _", () => {
  const f = finding("src/a.ts", "~2", "__init__ skips the base class");
  const text = `${renderReviewFinding(f)}\n\nℹ️ Showing top 1 of 3 candidate findings.\n\n---\n_This comment was generated by AI review bot._`;
  assert.deepEqual(parseReviewFindings(text), [f]);
});

test("parseReviewFindings: mixed formats keep the labelled why", () => {
  const why = (text) => parseReviewFindings(text).map((f) => f.why);
  assert.deepEqual(why("- [high] T\n`src/a.ts:42`\nWhy: x may be null."), ["x may be null."]);
  assert.deepEqual(why("- [high] T\nWhy: real reason\n`src/a.ts:~42`\nextra note"), ["real reason"]);
  // A separator or the italic disclaimer right after `file:line` is not a why.
  assert.deepEqual(why("- [high] T\n`src/a.ts:42`\n_This comment was generated by AI review bot._"), []);
  assert.deepEqual(why("- [high] T\n`src/a.ts:42`\n----- separator"), []);
});

